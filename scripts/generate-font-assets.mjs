import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(
  root,
  "scripts/font-sources/TeXGyreHerosCn-Bold.otf"
);
const target = resolve(
  root,
  "src/assets/texGyreHerosCondensed.generated.ts"
);
const fontBytes = readFileSync(source);
const buffer = fontBytes.buffer.slice(
  fontBytes.byteOffset,
  fontBytes.byteOffset + fontBytes.byteLength
);
const font = opentype.parse(buffer);

// TeX Gyre Heros Condensed Bold is an open-source Helvetica-compatible face.
// Its dimensions are calibrated for the renderer's 8 dpmm dot grid.
const advanceScale = 0.7;
const verticalScale = 1.071429;
const topOffsetRatio = -1 / 42;
const transformedM = font.charToGlyph("M");
const mAdvance = transformedM.advanceWidth || font.unitsPerEm;
const advances = Array.from({ length: 256 }, (_, codePoint) => {
  const glyph = font.charToGlyph(String.fromCodePoint(codePoint));
  return Number(
    (
      ((glyph.advanceWidth || mAdvance) / mAdvance)
      * advanceScale
    ).toFixed(6)
  );
});
const encoded = Buffer.from(fontBytes).toString("base64");
const chunks = encoded.match(/.{1,100}/g) ?? [];
const sourceHash = createHash("sha256").update(fontBytes).digest("hex");

const output = `// Generated by scripts/generate-font-assets.mjs. Do not edit by hand.
// TeX Gyre Heros Condensed Bold 2.004. See THIRD_PARTY_NOTICES.md.
export const TEX_GYRE_HEROS_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};
export const TEX_GYRE_HEROS_ADVANCE_SCALE = ${advanceScale};
export const TEX_GYRE_HEROS_VERTICAL_SCALE = ${verticalScale};
export const TEX_GYRE_HEROS_TOP_OFFSET_RATIO = ${topOffsetRatio};
export const TEX_GYRE_HEROS_ADVANCE_RATIOS: readonly number[] = Object.freeze(${JSON.stringify(
  advances
)});
const TEX_GYRE_HEROS_OTF_BASE64 = [
${chunks.map((chunk) => `  ${JSON.stringify(chunk)},`).join("\n")}
].join("");

let decoded: Uint8Array | undefined;

/** Returns the stable bundled open-source scalable resident-font bytes. */
export function texGyreHerosCondensedOtf(): Uint8Array {
  if (!decoded) {
    const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    const bytes: number[] = [];
    let value = 0;
    let bits = 0;
    for (const character of TEX_GYRE_HEROS_OTF_BASE64.replace(/=+$/, "")) {
      value = (value << 6) | alphabet.indexOf(character);
      bits += 6;
      if (bits >= 8) {
        bits -= 8;
        bytes.push((value >> bits) & 0xff);
      }
    }
    decoded = Uint8Array.from(bytes);
  }
  return decoded;
}
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);
